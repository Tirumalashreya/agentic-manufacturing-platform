// Report builders for the Agent Console demo.
//
// These are pure functions over data the pipeline already returned —
// nothing here calls the LLM or fabricates a figure. The shapes mirror
// real O2C (order-to-cash) checkpoint documents:
//   - Credit Agent    -> a Credit Management / credit exposure report
//   - Stock Agent     -> an ATP (available-to-promise) report
//   - Workflow        -> a document-flow / process audit report
//   - Order creation  -> a Sales Order Confirmation
// A stage that has nothing decision-worthy to show (Intent, Understanding,
// Entity Resolution, Context lookup) has no report — real O2C systems
// don't produce a "document" for an internal data-lookup step either.
import type { WorkflowResult } from "@/types/workflow";

export type ReportRow = { label: string; value: string };
export type ReportSection = { heading: string; rows: ReportRow[] };
export type ReportTable = { headers: string[]; rows: string[][] };
export type ReportChip = { label: string; tone: "ok" | "warn" | "bad" | "neutral" };

export type ReportDoc = {
  kind: "STAGE" | "WORKFLOW" | "SALES_ORDER";
  docType: string; // e.g. "CREDIT MANAGEMENT REPORT"
  docNumber: string;
  generatedAt: string;
  statusChip?: ReportChip;
  meta: ReportRow[];
  sections: ReportSection[];
  table?: ReportTable;
  totalsRow?: ReportRow;
  footerNote: string;
};

function money(n: unknown): string {
  const v = typeof n === "number" ? n : Number(n ?? 0);
  return Number.isFinite(v) ? v.toLocaleString(undefined, { maximumFractionDigits: 2 }) : "—";
}

function shortId(seed: string | null | undefined, prefix: string): string {
  const raw = (seed ?? Date.now().toString(36)).toString();
  const tail = raw.replace(/-/g, "").slice(-8).toUpperCase();
  return `${prefix}-${tail}`;
}

export function buildCreditStageReport(result: WorkflowResult): ReportDoc {
  const o = (result.stages ?? []).find((s) => s.node === "composed_execution")?.output ?? result;
  const limit = result.customer_credit_limit as number | undefined;

  if (result.status === "CUSTOMER_NOT_FOUND") {
    return {
      kind: "STAGE",
      docType: "CREDIT MANAGEMENT REPORT",
      docNumber: shortId(result.run_id, "CR"),
      generatedAt: new Date().toLocaleString(),
      statusChip: { label: "NOT ON FILE", tone: "bad" },
      meta: [
        { label: "Customer (as given)", value: String(result.customer ?? "—") },
        { label: "Requested by", value: "Agent Console — automated checkpoint" },
      ],
      sections: [
        {
          heading: "Credit Exposure Assessment",
          rows: [{ label: "Result", value: "No matching customer record in the ERP — credit could not be evaluated" }],
        },
      ],
      footerNote:
        "This customer has no record in the system, so there is no credit limit to check against. A customer master record must be created before an order can be placed.",
    };
  }

  const withinLimit = Boolean(o.credit_within_limit);
  return {
    kind: "STAGE",
    docType: "CREDIT MANAGEMENT REPORT",
    docNumber: shortId(result.run_id, "CR"),
    generatedAt: new Date().toLocaleString(),
    statusChip: withinLimit
      ? { label: "WITHIN LIMIT", tone: "ok" }
      : { label: "EXCEEDS LIMIT", tone: "bad" },
    meta: [
      { label: "Customer", value: String(result.customer_name ?? "—") },
      { label: "Customer ID", value: String(result.customer_id ?? "—") },
      { label: "Requested by", value: "Agent Console — automated checkpoint" },
    ],
    sections: [
      {
        heading: "Credit Exposure Assessment",
        rows: [
          { label: "Existing Exposure (open orders)", value: money(o.credit_existing_exposure) },
          { label: "This Order's Value", value: money((result.pending_approval?.preview.estimated_value) ?? o.credit_total_exposure) },
          { label: "Total Exposure If Approved", value: money(o.credit_total_exposure) },
          { label: "Approved Credit Limit", value: limit !== undefined ? money(limit) : "—" },
        ],
      },
    ],
    footerNote:
      "Generated by the Credit Agent as an automated checkpoint during order processing. This is a system-generated exposure check, not a substitute for a manual credit review.",
  };
}

export function buildStockStageReport(result: WorkflowResult): ReportDoc {
  const o = (result.stages ?? []).find((s) => s.node === "composed_execution")?.output ?? result;
  const sufficient = Boolean(o.stock_sufficient);
  const requestedQty = (result.pending_approval?.preview.quantity as number | undefined) ?? (result.quantity as number | undefined);
  const total = o.stock_total as number | undefined;
  const shortfall = sufficient || requestedQty === undefined || total === undefined ? null : Math.max(0, requestedQty - total);
  return {
    kind: "STAGE",
    docType: "AVAILABILITY (ATP) REPORT",
    docNumber: shortId(result.run_id, "AV"),
    generatedAt: new Date().toLocaleString(),
    statusChip: sufficient ? { label: "AVAILABLE", tone: "ok" } : { label: "INSUFFICIENT STOCK", tone: "bad" },
    meta: [
      { label: "Product", value: String(result.product_name ?? "—") },
      { label: "Product ID", value: String(result.product_id ?? "—") },
      { label: "Requested by", value: "Agent Console — automated checkpoint" },
    ],
    sections: [
      {
        heading: "Available-to-Promise Check",
        rows: [
          { label: "Requested Quantity", value: requestedQty !== undefined ? String(requestedQty) : "—" },
          { label: "Total Available (all plants)", value: total !== undefined ? String(total) : "—" },
          ...(shortfall !== null && shortfall > 0 ? [{ label: "Shortfall", value: String(shortfall) }] : []),
        ],
      },
    ],
    footerNote:
      "Generated by the Stock Agent as an automated ATP checkpoint. Figures are drawn directly from current inventory records at the time of the request.",
  };
}

export function buildWorkflowReport(
  result: WorkflowResult,
  displayStages: { label: string; decision?: string; icon: string }[]
): ReportDoc {
  const table: ReportTable = {
    headers: ["Step", "Agent / Stage", "Outcome"],
    rows: displayStages.map((s, i) => [String(i + 1), `${s.icon} ${s.label}`, s.decision ?? "Completed"]),
  };
  const statusTone: ReportChip["tone"] =
    result.status === "COMPLETED" || result.sales_order_id
      ? "ok"
      : result.status === "AWAITING_APPROVAL"
      ? "warn"
      : result.status === "ON_CREDIT_HOLD" || result.status === "REJECTED"
      ? "bad"
      : "neutral";
  return {
    kind: "WORKFLOW",
    docType: "WORKFLOW AUDIT REPORT",
    docNumber: shortId(result.run_id, "WF"),
    generatedAt: new Date().toLocaleString(),
    statusChip: { label: result.status ?? "IN PROGRESS", tone: statusTone },
    meta: [
      { label: "Customer Request", value: result.user_message },
      { label: "Entry Type", value: String(result.entry_type ?? "—") },
    ],
    sections: [],
    table,
    footerNote:
      "This report reflects the complete sequence of AI agent decisions for this request, including any human approval checkpoint. It is a process audit trail, not a legal or financial document.",
  };
}

export function buildSalesOrderReport(
  context: Record<string, unknown>,
  outcome: {
    sales_order_id?: string;
    sales_order_status?: string;
    sales_order_total?: number;
    fulfillment_strategy?: string | null;
    fulfillment_reasoning?: string | null;
    fulfillment_status?: string | null;
    delivery_id?: string | null;
    invoice_id?: string | null;
    invoice_status?: string | null;
    invoice_amount?: number | null;
  },
  approvedAt: string
): ReportDoc {
  const qty = Number(context.quantity ?? 0);
  const price = Number(context.price ?? 0);
  const sections: ReportSection[] = [
    {
      heading: "Approval Record",
      rows: [
        { label: "Decision", value: "APPROVED" },
        { label: "Approval Method", value: "Human-in-the-loop (Agent Console)" },
        { label: "Approved At", value: approvedAt },
      ],
    },
  ];

  if (outcome.fulfillment_strategy) {
    const rows: ReportRow[] = [{ label: "Strategy", value: outcome.fulfillment_strategy }];
    if (outcome.invoice_id) {
      rows.push(
        { label: "Delivery", value: outcome.delivery_id ?? "—" },
        { label: "Invoice", value: outcome.invoice_id },
        { label: "Invoiced Amount", value: money(outcome.invoice_amount ?? 0) }
      );
    } else {
      rows.push({ label: "Status", value: outcome.fulfillment_status ?? "Pending" });
    }
    sections.push({ heading: "Fulfillment", rows });
  }

  return {
    kind: "SALES_ORDER",
    docType: "SALES ORDER CONFIRMATION",
    docNumber: outcome.sales_order_id ?? "—",
    generatedAt: new Date().toLocaleString(),
    statusChip: { label: outcome.sales_order_status ?? "CONFIRMED", tone: "ok" },
    meta: [
      { label: "Sold-To Customer", value: String(context.customer_name ?? "—") },
      { label: "Customer ID", value: String(context.customer_id ?? "—") },
    ],
    sections,
    table: {
      headers: ["Product", "Qty", "Unit Price", "Line Total"],
      rows: [[String(context.product_name ?? "—"), String(qty), money(price), money(qty * price)]],
    },
    totalsRow: { label: "Order Total", value: money(outcome.sales_order_total ?? qty * price) },
    footerNote:
      "This sales order was created following an AI-assisted order-processing workflow with mandatory human approval prior to creation.",
  };
}
